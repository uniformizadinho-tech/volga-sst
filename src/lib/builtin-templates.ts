/**
 * Converte URLs antigas (arquivos com "#"/acentos, que o servidor não entrega)
 * para os nomes atuais. Modelos salvos antes desta correção continuam abrindo.
 */
export function normalizeOriginalTemplateUrl(url: string): string {
  if (!url) return url;
  return url
    .replaceAll("%23U00e1sico", "asico")
    .replaceAll("#U00e1sico", "asico")
    .replaceAll("%23U00f3rtico", "ortico")
    .replaceAll("#U00f3rtico", "ortico")
    .replaceAll("Básico", "Basico")
    .replaceAll("Pórtico", "Portico");
}

export function isBuiltInTemplateId(id: string): boolean {
  return id.startsWith(BUILTIN_PREFIX);
}

