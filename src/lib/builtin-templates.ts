/** Prepara a lista final: built-ins primeiro, seguidos dos salvos pelo usuário
 * (deduplicando por id caso um built-in acabe salvo por engano). */
export function withBuiltIns(list: SavedTemplate[]): SavedTemplate[] {
  const userOnly = list.filter((t) => !isBuiltInTemplateId(t.id));
  return [...BUILTIN_TEMPLATES, ...userOnly];
}

/** Remove os built-ins antes de persistir (localStorage/nuvem). */
export function stripBuiltIns(list: SavedTemplate[]): SavedTemplate[] {
  return list.filter((t) => !isBuiltInTemplateId(t.id));
}

/**
 * Retorna o instrutor originalmente "assado" no PPTX do modelo built-in
 * correspondente à URL, para que a geração possa substituí-lo pelo instrutor
 * escolhido no formulário. Retorna null quando a URL não corresponde a um
 * template built-in conhecido.
 */
export function getOriginalInstructorByTemplateUrl(
  url: string | undefined,
): { nome: string; cargo: string; registro: string } | null {
  if (!url) return null;
  const normalized = normalizeOriginalTemplateUrl(url);
  const t = BUILTIN_TEMPLATES.find(
    (tpl) =>
      tpl.shared.templateUrl && normalizeOriginalTemplateUrl(tpl.shared.templateUrl) === normalized,
  );
  if (!t) return null;
  return {
    nome: t.shared.instrutorNome,
    cargo: t.shared.instrutorCargo,
    registro: t.shared.instrutorRegistro,
  };
}
